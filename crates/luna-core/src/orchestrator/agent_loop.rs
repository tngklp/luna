//! The agent loop: streaming turns, tool dispatch, approvals, cancellation.

use crate::error::{Error, Result};
use crate::event::{EventKind, LunaEvent};
use crate::provider::types::{CompletionRequest, ContentBlock, Message, StopReason, StreamChunk};
use crate::provider::Provider;
use crate::tool::permissions::{Decision, PermissionGate};
use crate::tool::registry::ToolRegistry;
use std::sync::Arc;
use tokio_util::sync::CancellationToken;

/// Static description of one agent.
#[derive(Debug, Clone)]
pub struct AgentSpec {
    pub name: String,
    pub provider_key: String,
    pub model: String,
    pub system: Option<String>,
    /// Tool names allowed for this agent; empty = all registered.
    pub tools: Vec<String>,
    pub max_iterations: u32,
    pub max_tokens: u32,
    pub temperature: f32,
}

/// Everything the loop needs to run.
pub struct AgentContext {
    pub provider: Arc<dyn Provider>,
    pub tools: ToolRegistry,
    pub gate: Arc<PermissionGate>,
    pub bus: crate::event::EventBus,
    pub session_id: uuid::Uuid,
    /// Resolves interactive approvals (wired to the UI by the frontend).
    pub approvals: Arc<dyn ApprovalSink>,
}

/// Approvals are surfaced to the attached UI and resolved asynchronously.
#[async_trait::async_trait]
pub trait ApprovalSink: Send + Sync {
    /// Returns the user's decision. Implementations must honor `cancel`.
    ///
    /// `request_id` is generated by the loop and already published via
    /// `EventKind::ApprovalRequested`; implementations correlate responses
    /// with it.
    async fn request_approval(
        &self,
        request_id: uuid::Uuid,
        agent_id: &str,
        tool_name: &str,
        arguments: &serde_json::Value,
        cancel: &CancellationToken,
    ) -> bool;
}

/// Approve everything (used in tests and headless runs).
pub struct AutoApprove;

#[async_trait::async_trait]
impl ApprovalSink for AutoApprove {
    async fn request_approval(
        &self,
        _request_id: uuid::Uuid,
        _agent_id: &str,
        _tool_name: &str,
        _arguments: &serde_json::Value,
        _cancel: &CancellationToken,
    ) -> bool {
        true
    }
}

/// Deny everything (used in tests).
pub struct DenyAll;

#[async_trait::async_trait]
impl ApprovalSink for DenyAll {
    async fn request_approval(
        &self,
        _request_id: uuid::Uuid,
        _agent_id: &str,
        _tool_name: &str,
        _arguments: &serde_json::Value,
        _cancel: &CancellationToken,
    ) -> bool {
        false
    }
}

/// Runs the agentic loop until the model stops calling tools or limits hit.
pub struct AgentRunner {
    pub spec: AgentSpec,
}

impl AgentRunner {
    pub fn new(spec: AgentSpec) -> Self {
        Self { spec }
    }

    fn tool_specs(&self, tools: &ToolRegistry) -> Vec<crate::provider::types::ToolSpec> {
        if self.spec.tools.is_empty() {
            tools.specs()
        } else {
            tools
                .specs()
                .into_iter()
                .filter(|s| self.spec.tools.iter().any(|t| t == &s.name))
                .collect()
        }
    }

    /// Run the loop to completion starting from `history`.
    ///
    /// Returns the full history including the final assistant message.
    pub async fn run(
        &self,
        ctx: &AgentContext,
        history: &mut Vec<Message>,
        cancel: CancellationToken,
    ) -> Result<String> {
        let agent_id = self.spec.name.clone();
        ctx.bus.publish(LunaEvent::new(ctx.session_id, Some(agent_id.clone()), EventKind::RunStarted));

        let mut iterations: u32 = 0;
        let mut final_text = String::new();

        loop {
            if cancel.is_cancelled() {
                ctx.bus.publish(LunaEvent::new(
                    ctx.session_id,
                    Some(agent_id.clone()),
                    EventKind::RunFinished { summary: None, error: Some("cancelled".into()) },
                ));
                return Err(Error::Cancelled);
            }
            iterations += 1;
            if iterations > self.spec.max_iterations {
                let e = Error::MaxIterations(self.spec.max_iterations);
                ctx.bus.publish(LunaEvent::new(
                    ctx.session_id,
                    Some(agent_id.clone()),
                    EventKind::RunFinished { summary: None, error: Some(e.to_string()) },
                ));
                return Err(e);
            }

            let request = CompletionRequest {
                model: self.spec.model.clone(),
                system: self.spec.system.clone(),
                messages: history.clone(),
                tools: self.tool_specs(&ctx.tools),
                max_tokens: self.spec.max_tokens,
                temperature: self.spec.temperature,
            };

            // One streaming turn.
            let mut stream = ctx.provider.stream_completion(request, cancel.clone()).await?;
            let mut text = String::new();
            let mut tool_calls: Vec<(String, String, serde_json::Value)> = Vec::new();
            let mut stop_reason = StopReason::EndTurn;

            while let Some(chunk) = stream.next().await {
                match chunk {
                    StreamChunk::TextDelta(t) => {
                        text.push_str(&t);
                        ctx.bus.publish(LunaEvent::new(
                            ctx.session_id,
                            Some(agent_id.clone()),
                            EventKind::TokenDelta(t),
                        ));
                    }
                    StreamChunk::ToolUse { id, name, input } => {
                        tool_calls.push((id, name, input));
                    }
                    StreamChunk::Usage { .. } => {}
                    StreamChunk::Done { stop_reason: sr } => {
                        stop_reason = sr;
                        break;
                    }
                }
            }

            if cancel.is_cancelled() {
                ctx.bus.publish(LunaEvent::new(
                    ctx.session_id,
                    Some(agent_id.clone()),
                    EventKind::RunFinished { summary: None, error: Some("cancelled".into()) },
                ));
                return Err(Error::Cancelled);
            }

            // Record the assistant message (text + tool uses).
            let mut blocks = Vec::new();
            if !text.is_empty() {
                blocks.push(ContentBlock::Text { text: text.clone() });
            }
            for (id, name, input) in &tool_calls {
                blocks.push(ContentBlock::ToolUse { id: id.clone(), name: name.clone(), input: input.clone() });
            }
            if !blocks.is_empty() {
                history.push(Message { role: crate::provider::types::Role::Assistant, content: blocks });
            }
            if !text.is_empty() {
                final_text = text.clone();
                ctx.bus.publish(LunaEvent::new(
                    ctx.session_id,
                    Some(agent_id.clone()),
                    EventKind::AssistantMessage(text),
                ));
            }

            if tool_calls.is_empty() || stop_reason == StopReason::Cancelled {
                ctx.bus.publish(LunaEvent::new(
                    ctx.session_id,
                    Some(agent_id.clone()),
                    EventKind::RunFinished { summary: Some(final_text.clone()), error: None },
                ));
                return Ok(final_text);
            }

            // Dispatch tool calls sequentially (deterministic ordering).
            for (call_id, name, input) in tool_calls {
                let outcome = self
                    .execute_tool(ctx, &agent_id, &call_id, &name, &input, &cancel)
                    .await;
                let (content, is_error) = match outcome {
                    Ok(o) => (o.content, o.is_error),
                    Err(Error::Cancelled) => {
                        ctx.bus.publish(LunaEvent::new(
                            ctx.session_id,
                            Some(agent_id.clone()),
                            EventKind::RunFinished { summary: None, error: Some("cancelled".into()) },
                        ));
                        return Err(Error::Cancelled);
                    }
                    Err(e) => (format!("tool error: {e}"), true),
                };
                history.push(Message::tool_result(call_id, content, is_error));
            }
        }
    }

    async fn execute_tool(
        &self,
        ctx: &AgentContext,
        agent_id: &str,
        call_id: &str,
        name: &str,
        input: &serde_json::Value,
        cancel: &CancellationToken,
    ) -> Result<crate::tool::registry::ToolOutcome> {
        ctx.bus.publish(LunaEvent::new(
            ctx.session_id,
            Some(agent_id.to_string()),
            EventKind::ToolCallRequested {
                call_id: call_id.to_string(),
                name: name.to_string(),
                arguments: input.clone(),
            },
        ));

        // Permission gate first (registry-aware: honors tool approval flags).
        match ctx.gate.evaluate_with_registry(name, input, &ctx.tools) {
            Decision::Allowed => {}
            Decision::Denied(reason) => {
                return Ok(crate::tool::registry::ToolOutcome::err(format!(
                    "denied by permission policy: {reason}"
                )));
            }
            Decision::NeedsApproval => {
                let request_id = uuid::Uuid::new_v4();
                ctx.bus.publish(LunaEvent::new(
                    ctx.session_id,
                    Some(agent_id.to_string()),
                    EventKind::ApprovalRequested {
                        request_id,
                        agent_id: agent_id.to_string(),
                        tool_name: name.to_string(),
                        arguments: input.clone(),
                    },
                ));
                let approved = ctx
                    .approvals
                    .request_approval(request_id, agent_id, name, input, cancel)
                    .await;
                ctx.bus.publish(LunaEvent::new(
                    ctx.session_id,
                    Some(agent_id.to_string()),
                    EventKind::ApprovalResolved { request_id, approved },
                ));
                if !approved {
                    return Ok(crate::tool::registry::ToolOutcome::err(
                        "denied by user".to_string(),
                    ));
                }
            }
        }

        let tool = match ctx.tools.get(name) {
            Some(t) => t,
            None => {
                return Ok(crate::tool::registry::ToolOutcome::err(format!(
                    "unknown tool `{name}`"
                )))
            }
        };

        let result = tool.execute(input.clone(), cancel.clone()).await;
        let outcome = match result {
            Ok(o) => o,
            Err(Error::Cancelled) => return Err(Error::Cancelled),
            Err(e) => crate::tool::registry::ToolOutcome::err(e.to_string()),
        };

        ctx.bus.publish(LunaEvent::new(
            ctx.session_id,
            Some(agent_id.to_string()),
            EventKind::ToolCallFinished {
                call_id: call_id.to_string(),
                name: name.to_string(),
                outcome: outcome.clone(),
            },
        ));
        Ok(outcome)
    }
}

use futures::StreamExt;

#[cfg(test)]
mod tests {
    use super::*;
    use crate::provider::mock::{MockProvider, ScriptedTurn};
    use crate::tool::builtin;
    use serde_json::json;
    use std::sync::Mutex;

    fn spec() -> AgentSpec {
        AgentSpec {
            name: "tester".into(),
            provider_key: "mock".into(),
            model: "mock-1".into(),
            system: None,
            tools: vec![],
            max_iterations: 5,
            max_tokens: 1024,
            temperature: 0.0,
        }
    }

    fn ctx_with(provider: Arc<dyn Provider>, approvals: Arc<dyn ApprovalSink>) -> AgentContext {
        let mut tools = ToolRegistry::new();
        builtin::register_all(&mut tools);
        AgentContext {
            provider,
            tools,
            // shell requires approval per its registry flag; auto-approve here.
            gate: Arc::new(PermissionGate::new(PermissionGate::default_rules(), vec![])),
            bus: crate::event::EventBus::default(),
            session_id: uuid::Uuid::new_v4(),
            approvals,
        }
    }

    #[tokio::test]
    async fn plain_text_turn() {
        let provider = Arc::new(MockProvider::new(vec![ScriptedTurn::Text("hello!".into())]));
        let ctx = ctx_with(provider, Arc::new(AutoApprove));
        let mut history = vec![Message::user("hi")];
        let out = AgentRunner::new(spec()).run(&ctx, &mut history, CancellationToken::new()).await.unwrap();
        assert_eq!(out, "hello!");
    }

    #[tokio::test]
    async fn tool_loop_roundtrip() {
        let dir = tempfile::tempdir().unwrap();
        let file = dir.path().join("note.txt");
        std::fs::write(&file, "luna was here").unwrap();

        let provider = Arc::new(MockProvider::new(vec![
            ScriptedTurn::ToolCalls {
                text: "reading the file".into(),
                calls: vec![(
                    "c1".into(),
                    "read_file".into(),
                    json!({"path": file.to_string_lossy()}),
                )],
            },
            ScriptedTurn::Text("the file says: luna was here".into()),
        ]));
        let ctx = ctx_with(provider, Arc::new(AutoApprove));
        let mut history = vec![Message::user("read note.txt")];
        let out = AgentRunner::new(spec()).run(&ctx, &mut history, CancellationToken::new()).await.unwrap();
        assert!(out.contains("luna was here"));
        // history: user, assistant(tool_use), tool_result, assistant(final)
        assert_eq!(history.len(), 4);
    }

    #[tokio::test]
    async fn denied_shell_returns_error_result() {
        let provider = Arc::new(MockProvider::new(vec![
            ScriptedTurn::ToolCalls {
                text: String::new(),
                calls: vec![("c1".into(), "shell".into(), json!({"command": "rm -rf /"}))],
            },
            ScriptedTurn::Text("understood, not doing that".into()),
        ]));
        // DenyAll sink: shell needs approval (registry flag), user denies.
        let ctx = ctx_with(provider, Arc::new(DenyAll));
        let mut history = vec![Message::user("delete everything")];
        let out = AgentRunner::new(spec()).run(&ctx, &mut history, CancellationToken::new()).await.unwrap();
        assert!(out.contains("not doing that"));
        // The tool result fed back must be an error.
        let tool_msg = history.iter().find(|m| m.role == crate::provider::types::Role::Tool).unwrap();
        match &tool_msg.content[0] {
            ContentBlock::ToolResult { is_error, content, .. } => {
                assert!(is_error);
                assert!(content.contains("denied"));
            }
            other => panic!("unexpected block: {other:?}"),
        }
    }

    #[tokio::test]
    async fn user_denial_blocks_tool() {
        let dir = tempfile::tempdir().unwrap();
        let target = dir.path().join("x.txt");

        let provider = Arc::new(MockProvider::new(vec![
            ScriptedTurn::ToolCalls {
                text: String::new(),
                calls: vec![(
                    "c1".into(),
                    "write_file".into(),
                    json!({"path": target.to_string_lossy(), "content": "y"}),
                )],
            },
            ScriptedTurn::Text("okay, skipping the write".into()),
        ]));
        let ctx = ctx_with(provider, Arc::new(DenyAll));
        let mut history = vec![Message::user("write x.txt")];
        let out = AgentRunner::new(spec()).run(&ctx, &mut history, CancellationToken::new()).await.unwrap();
        assert!(out.contains("skipping"));
        assert!(!target.exists());
    }

    #[tokio::test]
    async fn max_iterations_guard() {
        // Infinite tool-call loop must trip the guard.
        let turn = ScriptedTurn::ToolCalls {
            text: String::new(),
            calls: vec![("c1".into(), "read_file".into(), json!({"path": "."}))],
        };
        let provider = Arc::new(MockProvider::new(vec![
            turn.clone(), turn.clone(), turn.clone(), turn.clone(), turn.clone(), turn.clone(), turn,
        ]));
        let ctx = ctx_with(provider, Arc::new(AutoApprove));
        let mut history = vec![Message::user("loop forever")];
        let err = AgentRunner::new(spec()).run(&ctx, &mut history, CancellationToken::new()).await.unwrap_err();
        assert!(matches!(err, Error::MaxIterations(5)));
    }

    #[tokio::test]
    async fn cancellation_stops_run() {
        struct SlowProvider;
        #[async_trait::async_trait]
        impl Provider for SlowProvider {
            fn name(&self) -> &str {
                "slow"
            }
            async fn stream_completion(
                &self,
                _r: CompletionRequest,
                cancel: CancellationToken,
            ) -> Result<std::pin::Pin<Box<dyn futures::Stream<Item = StreamChunk> + Send>>> {
                let stream = futures::stream::unfold((), move |()| {
                    let cancel = cancel.clone();
                    async move {
                        tokio::time::sleep(std::time::Duration::from_millis(50)).await;
                        if cancel.is_cancelled() {
                            Some((StreamChunk::Done { stop_reason: StopReason::Cancelled }, ()))
                        } else {
                            Some((StreamChunk::TextDelta("x".into()), ()))
                        }
                    }
                });
                Ok(Box::pin(stream))
            }
        }
        let ctx = ctx_with(Arc::new(SlowProvider), Arc::new(AutoApprove));
        let cancel = CancellationToken::new();
        let c2 = cancel.clone();
        tokio::spawn(async move {
            tokio::time::sleep(std::time::Duration::from_millis(30)).await;
            c2.cancel();
        });
        let mut history = vec![Message::user("go")];
        let err = AgentRunner::new(spec()).run(&ctx, &mut history, cancel).await.unwrap_err();
        assert!(err.is_cancelled());
    }

    // Silence unused warning for Mutex import in some cfgs.
    #[allow(dead_code)]
    fn _unused(_: &Mutex<()>) {}
}
